// Package server connects generated routes and typed application bindings to
// the framework's Fiber HTTP runtime.
package server

import (
	"fmt"
	"net/url"
	"os"
	"strings"

	"github.com/a-h/templ"
	"github.com/gofiber/fiber/v3"
	"github.com/gofiber/fiber/v3/middleware/recover"

	"github.com/akashKarmakar02/meta/action"
	"github.com/akashKarmakar02/meta/formcsrf"
	"github.com/akashKarmakar02/meta/internal/httpserver"
	"github.com/akashKarmakar02/meta/internal/render"
	internalrouting "github.com/akashKarmakar02/meta/internal/routing"
	"github.com/akashKarmakar02/meta/loader"
	"github.com/akashKarmakar02/meta/observability"
	"github.com/akashKarmakar02/meta/routing"
)

// PageResolver and LayoutResolver match the functions generated by routegen.
type PageResolver func(routing.Route) (templ.Component, error)
type LayoutResolver func(routing.Route, templ.Component) (templ.Component, error)

// Config describes the generated route set and application-owned bindings.
// ClientDir points to a production Vite output directory containing the
// manifest and assets. DevOrigin selects the meta dev Vite proxy instead;
// only one may be set. An SSR-only application may omit both.
//
// TrustedOrigin is required for actions, and must be the browser-facing
// http(s) origin. Form-capable actions also require a CSRF manager constructed
// from an application-owned, persistent secret shared by all instances.
type Config struct {
	Routes             []routing.Route
	APIRoutes          []APIRoute
	Middleware         []fiber.Handler
	Policies           []Policy
	Observability      *observability.Config
	SSRPage            PageResolver
	BarePage           PageResolver
	VisualLayout       LayoutResolver
	Loaders            []loader.Binding
	Actions            []action.Binding
	TrustedOrigin      string
	CSRF               *formcsrf.Manager
	MaxActionBodyBytes int64
	ClientDir          string
	// PublicDir contains files served at root-relative URLs. An empty value
	// disables public file serving; missing directories may be created later.
	PublicDir string
	DevOrigin string
	// HealthCheck reserves GET /healthz for development readiness.
	HealthCheck bool
}

// New validates the configuration and returns a Fiber application with assets,
// action endpoints, and generated routes wired to the existing dispatchers.
// Callers own listening and shutdown. No Node process is used at runtime.
func New(cfg Config) (*fiber.App, error) {
	policies, err := compilePolicies(cfg.Policies)
	if err != nil {
		return nil, err
	}
	for _, middleware := range cfg.Middleware {
		if middleware == nil {
			return nil, fmt.Errorf("server: middleware must not be nil")
		}
	}
	if cfg.ClientDir != "" && cfg.DevOrigin != "" {
		return nil, fmt.Errorf("server: choose either ClientDir or DevOrigin")
	}
	if cfg.MaxActionBodyBytes < 0 {
		return nil, fmt.Errorf("server: MaxActionBodyBytes must not be negative")
	}
	if (len(cfg.Actions) != 0 || cfg.CSRF != nil) && !validOrigin(cfg.TrustedOrigin) {
		return nil, fmt.Errorf("server: actions and CSRF require an explicit trusted http(s) origin")
	}
	for _, binding := range cfg.Actions {
		if binding.FormCapable() && cfg.CSRF == nil {
			return nil, fmt.Errorf("server: form action %q requires a CSRF manager", binding.ID())
		}
	}
	registry, err := action.NewRegistry(cfg.Actions...)
	if err != nil {
		return nil, fmt.Errorf("server: actions: %w", err)
	}

	routes := make([]routing.Route, len(cfg.Routes))
	ids := make([]string, len(routes))
	for i, route := range cfg.Routes {
		route.Layouts = append([]routing.Layout(nil), route.Layouts...)
		if route.ID == "" || route.ID != route.SourceFile {
			return nil, fmt.Errorf("server: route ID must equal its nonempty source file")
		}
		if _, err := routing.NewRoute(route.Path, route.SourceFile, route.Mode, route.Layouts); err != nil {
			return nil, fmt.Errorf("server: invalid route: %w", err)
		}
		hasCatchAll := false
		segments := strings.Split(route.Path, "/")
		for i, segment := range segments {
			if segment == "+" {
				if i != len(segments)-1 || hasCatchAll {
					return nil, fmt.Errorf("server: route %q has a nonterminal catch-all", route.ID)
				}
				hasCatchAll = true
			}
		}
		if hasCatchAll != (route.CatchAll != "") {
			return nil, fmt.Errorf("server: route %q has inconsistent catch-all metadata", route.ID)
		}
		if cfg.HealthCheck && route.Path == "/healthz" {
			return nil, fmt.Errorf("server: /healthz is reserved when HealthCheck is enabled")
		}
		for _, prefix := range []string{"/_meta", "/assets", "/_go_meta_vite"} {
			if route.Path == prefix || strings.HasPrefix(route.Path, prefix+"/") {
				return nil, fmt.Errorf("server: route %q uses reserved path %q", route.Path, prefix)
			}
		}
		if route.Mode == routing.ModeSSR && (cfg.SSRPage == nil || cfg.BarePage == nil || cfg.VisualLayout == nil) {
			return nil, fmt.Errorf("server: SSR route %q requires generated page and layout resolvers", route.ID)
		}
		if route.Mode == routing.ModeCSR {
			if cfg.ClientDir == "" && cfg.DevOrigin == "" {
				return nil, fmt.Errorf("server: CSR route %q requires client assets", route.ID)
			}
			if len(route.Layouts) > 0 && route.Layouts[0].Mode == routing.ModeSSR && cfg.VisualLayout == nil {
				return nil, fmt.Errorf("server: CSR route %q requires a visual layout resolver", route.ID)
			}
		}
		routes[i] = route
		ids[i] = route.ID
	}
	apiByID := make(map[string]APIRoute, len(cfg.APIRoutes))
	ordered := append([]routing.Route(nil), routes...)
	for _, api := range cfg.APIRoutes {
		route, err := routing.NewRoute(api.Path, api.SourceFile, routing.ModeSSR, nil)
		if err != nil {
			return nil, fmt.Errorf("server: invalid API route: %w", err)
		}
		route.CatchAll = api.CatchAll
		for _, prefix := range []string{"/_meta", "/assets", "/_go_meta_vite", "/healthz"} {
			if route.Path == prefix || strings.HasPrefix(route.Path, prefix+"/") {
				return nil, fmt.Errorf("server: API route %q uses reserved path %q", route.Path, prefix)
			}
		}
		if len(api.Handlers) == 0 {
			return nil, fmt.Errorf("server: API route %q has no handlers", api.SourceFile)
		}
		for method, handler := range api.Handlers {
			switch method {
			case "GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS":
			default:
				return nil, fmt.Errorf("server: API route %q has unsupported method %q", api.SourceFile, method)
			}
			if handler == nil {
				return nil, fmt.Errorf("server: API route %q has nil %s handler", api.SourceFile, method)
			}
		}
		if _, exists := apiByID[route.ID]; exists {
			return nil, fmt.Errorf("server: duplicate API route %q", route.ID)
		}
		apiByID[route.ID] = api
		ordered = append(ordered, route)
	}
	if err := internalrouting.ValidateRoutes(ordered); err != nil {
		return nil, fmt.Errorf("server: routes: %w", err)
	}
	internalrouting.SortRoutes(ordered)
	loaders, err := loader.NewRegistry(ids, cfg.Loaders...)
	if err != nil {
		return nil, fmt.Errorf("server: loaders: %w", err)
	}
	var assets *httpserver.Assets
	if cfg.ClientDir != "" {
		a, err := httpserver.LoadAssets(cfg.ClientDir)
		if err != nil {
			return nil, fmt.Errorf("server: assets: %w", err)
		}
		assets = &a
	} else if cfg.DevOrigin != "" {
		a, err := httpserver.DevelopmentAssets(cfg.DevOrigin)
		if err != nil {
			return nil, fmt.Errorf("server: development assets: %w", err)
		}
		assets = &a
	}
	app := fiber.New(fiber.Config{ErrorHandler: render.HTTPErrorHandler, CaseSensitive: true})
	app.Use(recover.New())
	var telemetry observability.Config
	if cfg.Observability != nil {
		telemetry = *cfg.Observability
	}
	if telemetry.Logger == nil && !telemetry.DisableLogging && (cfg.DevOrigin != "" || os.Getenv("GO_META_DEV") == "1") {
		telemetry.Logger = observability.DevelopmentLogger(os.Stderr)
	}
	app.Use(observability.Middleware(telemetry))
	app.Use(httpserver.ValidatePagePath)
	for _, middleware := range cfg.Middleware {
		app.Use(middleware)
	}
	if cfg.ClientDir != "" {
		if err := httpserver.MountAssets(app, cfg.ClientDir); err != nil {
			return nil, fmt.Errorf("server: assets: %w", err)
		}
	}
	actionPolicies := append([]fiber.Handler{func(c fiber.Ctx) error {
		observability.SetRoute(c.Context(), "action")
		c.Set(fiber.HeaderCacheControl, "no-store")
		return c.Next()
	}}, policies.middleware()...)
	httpserver.MountActions(app, registry, httpserver.ActionEndpointConfig{TrustedOrigin: cfg.TrustedOrigin, CSRF: cfg.CSRF, MaxBodyBytes: cfg.MaxActionBodyBytes}, actionPolicies...)
	if cfg.HealthCheck {
		app.Get("/healthz", func(c fiber.Ctx) error { return c.SendString("ok") })
	}
	if err := httpserver.MountPublic(app, cfg.PublicDir); err != nil {
		return nil, fmt.Errorf("server: %w", err)
	}
	for _, route := range ordered {
		if api, ok := apiByID[route.ID]; ok {
			middleware := []fiber.Handler{httpserver.WithRouteParams(route, func(c fiber.Ctx) error { return c.Next() })}
			middleware = append(middleware, policies.middleware()...)
			MountAPI(app, api, middleware...)
			continue
		}
		var handler fiber.Handler
		switch route.Mode {
		case routing.ModeSSR:
			handler = render.SSRNavigationHandler(route, assets, render.PageResolver(cfg.SSRPage), render.PageResolver(cfg.BarePage), render.VisualLayoutResolver(cfg.VisualLayout))
		case routing.ModeCSR:
			handler = render.CSRNavigationHandler(route, assets, render.VisualLayoutResolver(cfg.VisualLayout))
		}
		handler = httpserver.WithLoader(loaders, route, handler)
		path := internalrouting.FiberRegistrationPath(route.Path)
		middleware := []fiber.Handler{httpserver.WithRouteParams(route, func(c fiber.Ctx) error { return c.Next() })}
		middleware = append(middleware, policies.middleware()...)
		if cfg.CSRF != nil {
			middleware = append(middleware, httpserver.WithFormCSRF(cfg.CSRF, cfg.TrustedOrigin))
		}
		handlers := make([]any, 0, len(middleware))
		for _, item := range middleware[1:] {
			handlers = append(handlers, item)
		}
		handlers = append(handlers, handler)
		app.Get(path, middleware[0], handlers...)
	}
	return app, nil
}

func validOrigin(origin string) bool {
	u, err := url.Parse(origin)
	if err != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Hostname() == "" || u.User != nil || u.Path != "" || u.RawQuery != "" || u.Fragment != "" || u.Opaque != "" {
		return false
	}
	return u.Host != "" && !strings.ContainsAny(u.Host, " \t\r\n")
}
