package codegen

import (
	"bytes"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"slices"
	"sort"
	"strconv"
	"strings"

	"go-meta/internal/routing"
)

// tsHeader is stamped on every generated TypeScript file.
const tsHeader = "// Code generated by go-meta route generator. DO NOT EDIT."

// RouteRegistryTS renders the client route import map for the discovered
// route set: a plain object mapping stable route IDs to static import()
// loader functions. Only CSR (.svelte) routes are included; SSR (.templ)
// pages never receive client component loaders.
//
// G04 adds two companion maps over the same manifest:
//   - layoutLoaders: stable layout IDs to static import() loaders for
//     client (layout.svelte) layouts — the deterministic, Vite-analyzable
//     way the runtime resolves a layout component for mounting.
//   - routeLayouts: route ID to its selected visual layout, so the
//     bootstrap can mount the right client layout
//     chain on a direct load, where no navigation envelope exists.
//
// Output is deterministic: routes emit in manifest (path-sorted) order,
// one entry per line, fixed formatting — byte-stable across runs for
// identical inputs. E06 contract: fixed file paths to import functions,
// no dynamic arbitrary imports; Vite statically analyzes each import()
// call at build time.
func RouteRegistryTS(m routing.Manifest) string {
	var b strings.Builder
	b.WriteString(tsHeader)
	b.WriteString("\n\n")
	b.WriteString("// Client route import map for CSR (page.svelte) routes.\n")
	b.WriteString("// Keys are stable source-derived route IDs shared with the Go manifest.\n\n")

	b.WriteString("export const pageLoaders: Record<string, () => Promise<{ default: unknown }>> = {\n")
	for _, r := range m.Routes {
		if r.Mode != routing.ModeCSR {
			continue
		}
		fmt.Fprintf(&b, "  %s: () => import(%s),\n",
			tsString(r.ID), tsString(importPathFor(r.SourceFile)))
	}
	b.WriteString("};\n")

	// Client layout components, keyed by stable layout ID, deduplicated
	// across routes and sorted so output never depends on route order.
	ids := make([]string, 0, len(m.Routes))
	for _, r := range m.Routes {
		for _, l := range r.Layouts {
			if l.Mode != routing.ModeCSR {
				continue
			}
			if !slices.Contains(ids, l.ID) {
				ids = append(ids, l.ID)
			}
		}
	}
	sort.Strings(ids)
	b.WriteString("\n// Client (layout.svelte) components keyed by stable layout ID (G04).\n")
	b.WriteString("export const layoutLoaders: Record<string, () => Promise<{ default: unknown }>> = {\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "  %s: () => import(%s),\n",
			tsString(id), tsString(layoutImportPathFor(id)))
	}
	b.WriteString("};\n")

	// Declared layout ancestry per route, outermost -> innermost, emitted
	// for every route (client code filters client-mountable entries).
	b.WriteString("\n// Selected visual layout per route ID.\n")
	b.WriteString("export const routeLayouts: Record<string, string[]> = {\n")
	for _, r := range m.Routes {
		if len(r.Layouts) == 0 {
			continue
		}
		chain := make([]string, 0, len(r.Layouts))
		for _, l := range r.Layouts {
			chain = append(chain, l.ID)
		}
		fmt.Fprintf(&b, "  %s: [%s],\n",
			tsString(r.ID), joinQuoted(chain))
	}
	b.WriteString("};\n")
	return b.String()
}

// layoutImportPathFor returns the Vite-resolvable import specifier for a
// client layout. Unlike page source files (relative to the app root),
// layout IDs already carry the app-prefixed form discovered by routing
// ("app/dashboard/layout.svelte"), so the specifier is the ID itself
// resolved against the generated registry's location in frontend/, whose
// sibling directory is the app tree.
func layoutImportPathFor(layoutID string) string {
	return path.Join("..", layoutID)
}

// joinQuoted renders a comma-separated quoted list of strings.
func joinQuoted(ids []string) string {
	parts := make([]string, len(ids))
	for i, id := range ids {
		parts[i] = tsString(id)
	}
	return strings.Join(parts, ", ")
}

// importPathFor returns the Vite-resolvable import specifier for a CSR
// page's source file, relative to the generated registry's location in
// frontend/. The app tree sits at ../app from frontend/.
func importPathFor(sourceFile string) string {
	return path.Join("..", "app", sourceFile)
}

// tsString quotes s as a double-quoted TypeScript string literal,
// escaping backslashes, double quotes, and control characters via
// strconv.Quote — safe for arbitrary route identifiers.
func tsString(s string) string {
	return strconv.Quote(s)
}

// WriteRouteRegistryTS generates and writes frontend/route-registry.generated.ts
// beneath dir. The caller passes the repo root; the output path is fixed
// by the generator, matching the blueprint's artifact location.
func WriteRouteRegistryTS(dir string, m routing.Manifest) error {
	dst := filepath.Join(dir, "frontend", "route-registry.generated.ts")
	src := RouteRegistryTS(m)
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return fmt.Errorf("codegen: create frontend directory: %w", err)
	}
	// Skip the write when the file already holds the exact bytes (P2-A03):
	// the output is deterministic for identical inputs, and rewriting an
	// unchanged file bumps its mtime, retriggering watchers (Air, Vite).
	// No-op regeneration leaves zero side effects.
	if current, err := os.ReadFile(dst); err == nil && bytes.Equal(current, []byte(src)) {
		return nil
	}
	if err := os.WriteFile(dst, []byte(src), 0o644); err != nil {
		return fmt.Errorf("codegen: write %s: %w", dst, err)
	}
	return nil
}
